let language = readLanguage();

function readLanguage() {
  try {
    const saved = localStorage.getItem(LANGUAGE_KEY);
    if (LANGUAGES.some((entry) => entry.code === saved)) return saved;
  } catch { /* private mode */ }
  return DEFAULT_LANGUAGE;
}

export function getLanguage() { return language; }

export function setLanguage(code) {
  if (!LANGUAGES.some((entry) => entry.code === code)) return language;
  language = code;
  try { localStorage.setItem(LANGUAGE_KEY, code); } catch { /* private mode */ }
  document.documentElement.setAttribute('lang', code);
  return language;
}

export function locale() {
  return (LANGUAGES.find((entry) => entry.code === language) || LANGUAGES[0]).locale;
}

/** Looks up a string and fills in {placeholders}. Falls back to the key. */
export function t(key, vars = {}) {
  const table = STRINGS[language] || STRINGS[DEFAULT_LANGUAGE];
  const fallback = STRINGS[DEFAULT_LANGUAGE][key] ?? key;
  const template = table[key] ?? fallback;
  return String(template).replace(/\{(\w+)\}/g, (match, name) =>
    (Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match));
}

/** Display label for a stored vocabulary value. Unknown values pass through. */
export function label(value) {
  if (value === null || value === undefined || value === '') return '';
  const table = ENUM_LABELS[language] || {};
  return table[value] ?? value;
}

/** Turns a list of stored values into {value, label} options for a <select>. */
export function options(values = []) {
  return values.map((value) => ({ value, label: label(value) }));
}

/**
 * Renders an activity entry in the reader's language from the structured
 * fields. Entries written before those fields existed fall back to the
 * sentence the server stored.
 */
export function activityText(entry) {
  const subject = entry.subject || '';
  if (!subject) return entry.summary || '';
  const key = `activity.${entry.entity_type}.${entry.action}`;
  const table = STRINGS[language] || STRINGS[DEFAULT_LANGUAGE];
  if (table[key]) return t(key, { subject: label(subject) });
  const generic = `activity.fallback.${entry.action}`;
  if (table[generic]) return t(generic, { subject: label(subject) });
  return entry.summary || subject;
}

